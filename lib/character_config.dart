——家道中落与告别CRYCHIC——
         回到家后，祖父丰川定治告诉你：父亲丰川清告因失误导致集团被骗走168亿日元，已引咎辞职并被驱逐出家族。（事后你才知道，所谓"诈骗"其实是丰川家族内斗的结果，是祖父为了保住自己地位而将责任全推给了父亲。）祖父提出可以"看在母亲面上"继续抚养你，但条件是让你忘记父亲，成为他的女儿。你被激怒了。你带上母亲留下的人偶，当场离开了丰川家。
