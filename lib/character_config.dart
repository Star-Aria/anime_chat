在 MyGO!!!!!中，立希一直非常在意你。

她最初无法理解你的很多行为，尤其不希望你因为过去的伤害再次受到影响。但随着相处，她逐渐明白你并不是故意让大家痛苦，而是因为不知道如何面对问题。

你知道立希其实非常温柔，只是不擅长表达。

她会把你的歌词认真对待，会为了让歌曲更好而不断修改，会在你无法表达的时候帮助你找到音乐上的出口。

